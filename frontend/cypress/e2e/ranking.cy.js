describe('Ranking', () => {
  it('mostra lista vazia e permite recuperar erro de consulta', () => {
    cy.intercept('GET', '/api/ranking', { body: [] }).as('ranking')
    cy.visit('/')
    cy.wait('@ranking')
    cy.get('[data-cy="ranking"]').should('contain.text', 'Nenhuma conclusão aprovada')
    cy.intercept('GET', '/api/ranking', { statusCode: 503 }).as('erroRanking')
    cy.contains('button', 'Atualizar ranking').click()
    cy.wait('@erroRanking')
    cy.get('[data-cy="ranking"]').should('contain.text', 'Não foi possível carregar o ranking')
    cy.intercept('GET', '/api/ranking', { body: [{ posicao: 1, alunoId: 1, nome: 'Aluno teste', aprovacoes: 3 }] }).as('recuperado')
    cy.contains('button', 'Atualizar ranking').click()
    cy.wait('@recuperado')
    cy.get('[data-cy="ranking"] tbody tr').should('have.length', 1).and('contain.text', 'Aluno teste')
  })

  it('consulta ranking real e atualiza após uma conclusão pela tela', () => {
    const nome = `Ranking ${Date.now()}`
    cy.request('POST', '/api/alunos', { nome, plano: 'Básico' }).its('body').as('alunoRanking')
    cy.request('POST', '/api/cursos', { nome }).its('body').as('cursoRanking')
    cy.intercept('GET', '/api/ranking').as('rankingReal')
    cy.intercept('GET', '/api/alunos').as('alunosRanking')
    cy.intercept('GET', '/api/cursos').as('cursosRanking')
    cy.visit('/')
    cy.wait(['@rankingReal', '@alunosRanking', '@cursosRanking'])
    cy.get('@alunoRanking').then(aluno => cy.get('[data-cy="selecionar-aluno"]').select(String(aluno.id)))
    cy.get('@cursoRanking').then(curso => cy.get('[data-cy="selecionar-curso"]').select(String(curso.id)))
    cy.get('[data-cy="nota"]').type('7')
    cy.get('[data-cy="concluido"]').check()
    cy.get('[data-cy="processar-conclusao"]').click()
    cy.wait('@rankingReal')
    cy.get('[data-cy="ranking"] tbody tr').contains('td', nome).parent().find('td').last().should('have.text', '1')
  })
})
